// Builds window/src/i18n/catalog.ts: for each language the engine's Control UI is translated into, the window's
// Settings words (screens/settings/nav.ts: group and page titles, ledes, card titles) that already have a reviewed
// translation in the Control UI's translation memory (engine/ui/src/i18n/.i18n/<lang>.tm.jsonl, exact English match).
// Words with no translation are left out, so they show in English. Private #1100.
//
// Usage (from the repo root): node window/scripts/build-window-locales.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const TM = "engine/ui/src/i18n/.i18n/";
const OUT = "window/src/i18n/catalog.ts";
/** Names that stay as they are in every language. */
const KEEP = new Set(["Branch", "Seedbank", "Git", "Trunk", "Trunks"]);

const nav = readFileSync("window/src/screens/settings/nav.ts", "utf8");
const words = new Set();
for (const m of nav.matchAll(/(?:title|lede): "([^"]+)"/g)) words.add(m[1]);
for (const m of nav.matchAll(/cards: \[([^\]]*)\]/g)) for (const c of m[1].matchAll(/"([^"]+)"/g)) words.add(c[1]);
for (const k of KEEP) words.delete(k);

const catalog = {};
for (const file of readdirSync(TM).filter((f) => f.endsWith(".tm.jsonl")).sort()) {
  const lang = file.replace(".tm.jsonl", "");
  const first = new Map();
  for (const line of readFileSync(TM + file, "utf8").split("\n")) {
    if (!line.trim()) continue;
    const row = JSON.parse(line);
    if (typeof row.text === "string" && typeof row.translated === "string" && row.translated.trim() && !first.has(row.text)) first.set(row.text, row.translated);
  }
  catalog[lang] = Object.fromEntries([...words].sort().filter((w) => first.has(w)).map((w) => [w, first.get(w)]));
}
const head = "// Generated by window/scripts/build-window-locales.mjs from the Control UI's translation memory. Do not edit by hand.\n";
writeFileSync(OUT, `${head}export const CATALOG: Record<string, Record<string, string>> = ${JSON.stringify(catalog, null, 1)};\n`);
console.log(`${OUT}: ${Object.keys(catalog).length} languages, ${Object.values(catalog)[0] ? Object.keys(Object.values(catalog)[0]).length : 0} words each of ${words.size}`);
