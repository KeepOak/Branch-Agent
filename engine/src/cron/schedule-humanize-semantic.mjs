import { fileURLToPath, pathToFileURL } from 'node:url';
const root=fileURLToPath(new URL('../../',import.meta.url)).replaceAll('\\','/').replace(/\/$/,'');
const deps=process.env.BRANCH_AUTOMATION_TEST_DEPENDENCY_ROOT;
const compilerPath=process.env.BRANCH_AUTOMATION_TYPESCRIPT_API_PATH;
if(!deps || !compilerPath) throw new Error('existing dependency root and TypeScript compiler API path are required');
const ts=(await import(pathToFileURL(compilerPath).href)).default;
const file=root+'/src/cron/schedule-humanize.ts';
const config=ts.readConfigFile(root+'/tsconfig.json',ts.sys.readFile);
if(config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText,'\n'));
const conversion=ts.convertCompilerOptionsFromJson(config.config.compilerOptions,root);
const options={...conversion.options,noEmit:true,types:['node'],typeRoots:[deps+'/node_modules/@types']};
const host=ts.createCompilerHost(options);
host.resolveModuleNames=(names,containingFile)=>names.map(name=>{
 const result=ts.resolveModuleName(name,containingFile,options,host).resolvedModule;
 if(result)return result;
 if(name.startsWith('.'))return undefined;
 return ts.resolveModuleName(name,containingFile.replace(root,deps),options,host).resolvedModule;
});
const program=ts.createProgram([file],options,host);
const errors=[...conversion.errors,...program.getOptionsDiagnostics(),...program.getSyntacticDiagnostics(program.getSourceFile(file)),...program.getSemanticDiagnostics(program.getSourceFile(file))];
for(const diagnostic of errors) process.stderr.write(ts.formatDiagnosticsWithColorAndContext([diagnostic],{getCurrentDirectory:()=>root,getCanonicalFileName:f=>f,getNewLine:()=> '\n'}));
process.stdout.write(JSON.stringify({root:file,dependencyFiles:program.getSourceFiles().length,errors:errors.length,scope:'actual selected module semantic diagnostics; dependencies resolved, their diagnostics not claimed'})+'\n');
process.exitCode=errors.length?1:0;
